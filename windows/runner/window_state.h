#ifndef RUNNER_WINDOW_STATE_H_
#define RUNNER_WINDOW_STATE_H_

#include <windows.h>

// Размер, положение и «развёрнуто» между запусками.
//
// Окно всегда открывалось 1280x720 в углу экрана: развернули, закрыли,
// открыли — снова маленькое. Состояние лежит в HKCU\Software\Impressions,
// рядом с самим приложением; прав администратора для этого не нужно.
namespace window_state {

// Наименьший осмысленный размер окна в логических точках.
//
// Уже 720 приложение остаётся рабочим, но перестаёт быть удобным: боковая
// панель занимает 76 точек, а панель отбора каталога складывается в один
// столбец. Минимума не было вовсе — окно сужалось до ширины заголовка.
constexpr int kMinWindowWidth = 720;
constexpr int kMinWindowHeight = 560;

// Возвращает окну прежние размер и положение.
//
// Ничего не делает, если сохранённого состояния нет или окно оказалось бы за
// пределами подключённых сейчас мониторов: второй монитор могли отключить.
void Restore(HWND window);

// Запоминает текущее состояние окна. Свёрнутое окно не запоминаем: открывать
// приложение сразу в панели задач никто не просил.
void Save(HWND window);

}  // namespace window_state

#endif  // RUNNER_WINDOW_STATE_H_
